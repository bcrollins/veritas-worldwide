#!/usr/bin/env node
/**
 * Generate src/data/recordOfJesusChristWaves.generated.ts from WaveN files.
 * Adding recordOfJesusChristWaveN.ts + re-running this script wires claims without
 * hand-editing the main merge list. Attribution: Veritas Worldwide only.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dataDir = path.join(root, 'src/data')
const outFile = path.join(dataDir, 'recordOfJesusChristWaves.generated.ts')

const waves = fs
  .readdirSync(dataDir)
  .filter((n) => /^recordOfJesusChristWave\d+\.ts$/.test(n))
  .map((n) => {
    const num = Number(n.match(/Wave(\d+)/)?.[1] || 0)
    return { num, file: n, exportName: `ROC_WAVE${num}_CLAIMS` }
  })
  .filter((w) => w.num >= 3) // wave files start at 3 (extras cover early)
  .sort((a, b) => a.num - b.num)

if (waves.length === 0) {
  console.error('[generate-roc-waves-barrel] no wave files found')
  process.exit(1)
}

// Validate each wave exports the expected const name
for (const w of waves) {
  const src = fs.readFileSync(path.join(dataDir, w.file), 'utf8')
  if (!src.includes(`export const ${w.exportName}`)) {
    console.error(`[generate-roc-waves-barrel] ${w.file} missing export const ${w.exportName}`)
    process.exit(1)
  }
}

const header = `/**
 * AUTO-GENERATED by scripts/generate-roc-waves-barrel.mjs — do not edit by hand.
 * Re-run: node scripts/generate-roc-waves-barrel.mjs
 * Attribution: Veritas Worldwide only.
 */
`
const imports = waves
  .map((w) => `import { ${w.exportName} } from './${w.file.replace(/\.ts$/, '')}'`)
  .join('\n')

const array = `export const ROC_WAVE_CLAIM_MAPS = [
${waves.map((w) => `  ${w.exportName},`).join('\n')}
] as const

export const ROC_WAVE_NUMBERS = [${waves.map((w) => w.num).join(', ')}] as const
`

const body = `${header}
${imports}

${array}
`

fs.writeFileSync(outFile, body)
console.log(
  `[generate-roc-waves-barrel] ${waves.length} waves (Wave${waves[0].num}–Wave${waves[waves.length - 1].num}) → ${path.relative(root, outFile)}`,
)
