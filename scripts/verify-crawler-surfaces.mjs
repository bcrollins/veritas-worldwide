#!/usr/bin/env node
/**
 * Regression guard for crawler-facing surface counts.
 * Fails if prerender, sitemap, or llms discovery shrink below production floors
 * or drop durable PDF / trust routes that operators and AI crawlers depend on.
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, '..')

// Floors sit ~10% under the 2026-07-16 production baseline (289 prerender / 383 sitemap)
// so legitimate content growth is free, but accidental drops still fail CI/local verify.
const MIN_PRERENDER_ROUTES = 250
const MIN_SITEMAP_URLS = 300
const MIN_LLMS_LINKS = 15

const REQUIRED_SITEMAP_PATHS = [
  '/',
  '/about',
  '/methodology',
  '/sources',
  '/terms',
  '/privacy',
  '/accessibility',
  '/institute',
  '/institute/book',
  '/search',
  '/the-record.pdf',
  '/veritas-institute-field-manual.pdf',
]

const REQUIRED_LLMS_NEEDLES = [
  'veritas-institute-field-manual.pdf',
  '/institute/book',
  '/methodology',
  '/sources',
  '/israel-dossier',
]

function assert(condition, message) {
  if (!condition) {
    console.error(`[verify:crawler-surfaces] FAIL — ${message}`)
    process.exit(1)
  }
}

function read(rel) {
  const full = path.join(root, rel)
  assert(fs.existsSync(full), `missing required file ${rel}`)
  return fs.readFileSync(full, 'utf8')
}

function countSitemapUrls(xml) {
  return (xml.match(/<url>/g) || []).length
}

function sitemapHasPath(xml, routePath) {
  const absolute = routePath === '/'
    ? 'https://veritasworldwide.com/'
    : `https://veritasworldwide.com${routePath}`
  // Accept with or without trailing slash variants for the root.
  if (routePath === '/') {
    return xml.includes('https://veritasworldwide.com</loc>') || xml.includes('https://veritasworldwide.com/</loc>')
  }
  return xml.includes(`${absolute}</loc>`) || xml.includes(absolute)
}

// ── Prerender manifest ────────────────────────────────────────────
const manifestCandidates = [
  'dist/prerender-manifest.json',
  'public/prerender-manifest.json',
]
let prerenderCount = 0
let manifestPath = ''
for (const candidate of manifestCandidates) {
  const full = path.join(root, candidate)
  if (!fs.existsSync(full)) continue
  try {
    const parsed = JSON.parse(fs.readFileSync(full, 'utf8'))
    const count = Object.keys(parsed || {}).length
    if (count > prerenderCount) {
      prerenderCount = count
      manifestPath = candidate
    }
  } catch (error) {
    console.warn(`[verify:crawler-surfaces] warn: could not parse ${candidate}: ${error.message}`)
  }
}

// Prefer live dist after postbuild; allow source-side floor via public sitemap alone in pure source checks.
if (manifestPath) {
  assert(
    prerenderCount >= MIN_PRERENDER_ROUTES,
    `prerender route count ${prerenderCount} from ${manifestPath} is below floor ${MIN_PRERENDER_ROUTES}`
  )
  console.log(`[verify:crawler-surfaces] prerender ${prerenderCount} routes (${manifestPath}) ≥ ${MIN_PRERENDER_ROUTES}`)
} else {
  console.warn('[verify:crawler-surfaces] no prerender manifest yet — run build/postbuild for full coverage; checking source sitemap/llms only')
}

// ── Sitemap ───────────────────────────────────────────────────────
// public/ is the committed crawler source of truth. dist/ is regenerated by
// postbuild and may be stale on a dirty local workspace — never fail path
// requirements solely because an old dist artifact lags the source sitemap.
const publicSitemapXml = read('public/sitemap.xml')
const distSitemapPath = path.join(root, 'dist/sitemap.xml')
const distSitemapXml = fs.existsSync(distSitemapPath) ? fs.readFileSync(distSitemapPath, 'utf8') : ''
const publicCount = countSitemapUrls(publicSitemapXml)
const distCount = distSitemapXml ? countSitemapUrls(distSitemapXml) : 0
const sitemapCount = Math.max(publicCount, distCount)
assert(
  publicCount >= MIN_SITEMAP_URLS,
  `public sitemap URL count ${publicCount} is below floor ${MIN_SITEMAP_URLS}`
)
console.log(
  `[verify:crawler-surfaces] sitemap public=${publicCount}` +
    (distCount ? ` dist=${distCount}` : '') +
    ` (effective ${sitemapCount}) ≥ ${MIN_SITEMAP_URLS}`
)

for (const routePath of REQUIRED_SITEMAP_PATHS) {
  assert(sitemapHasPath(publicSitemapXml, routePath), `public sitemap missing required path ${routePath}`)
}
console.log(`[verify:crawler-surfaces] public sitemap includes ${REQUIRED_SITEMAP_PATHS.length} required trust/PDF paths`)

if (distSitemapXml) {
  for (const routePath of ['/the-record.pdf', '/veritas-institute-field-manual.pdf']) {
    if (!sitemapHasPath(distSitemapXml, routePath)) {
      console.warn(
        `[verify:crawler-surfaces] warn: dist/sitemap.xml missing ${routePath} — run postbuild before deploy`
      )
    }
  }
}

// ── llms.txt ──────────────────────────────────────────────────────
// Same rule: public is authoritative; dist is best-effort after postbuild.
const llmsRel = 'public/llms.txt'
const llmsText = read(llmsRel)
const llmsLinks = (llmsText.match(/https:\/\/veritasworldwide\.com[^\s)]+/g) || []).length
assert(
  llmsLinks >= MIN_LLMS_LINKS,
  `llms.txt link count ${llmsLinks} from ${llmsRel} is below floor ${MIN_LLMS_LINKS}`
)
for (const needle of REQUIRED_LLMS_NEEDLES) {
  assert(llmsText.includes(needle), `llms.txt missing required needle ${needle}`)
}
console.log(`[verify:crawler-surfaces] llms ${llmsLinks} links (${llmsRel}) ≥ ${MIN_LLMS_LINKS}`)

// ── Source trust pages still advertise durable Field Manual PDF ───
const trustPages = [
  'src/pages/AboutPage.tsx',
  'src/pages/MethodologyPage.tsx',
  'src/pages/SourcesPage.tsx',
  'src/pages/PrivacyPage.tsx',
  'src/pages/TermsPage.tsx',
  'src/pages/AccessibilityPage.tsx',
]
for (const page of trustPages) {
  const text = read(page)
  assert(
    text.includes('/veritas-institute-field-manual.pdf'),
    `${page} is missing Field Manual PDF trust link`
  )
  assert(
    text.includes('/institute/book') || text.includes("to: '/institute/book'") || text.includes('to="/institute/book"'),
    `${page} is missing Field Manual route link`
  )
}
console.log(`[verify:crawler-surfaces] ${trustPages.length} trust pages link Field Manual + PDF`)

console.log('[verify:crawler-surfaces] PASS')
